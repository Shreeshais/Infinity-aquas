import { writeFile } from 'node:fs/promises';

// Support standard Netlify environment variable names
const key = process.env.GEMINI_API_KEY
  || process.env.INFINITY_GEMINI_API_KEY
  || process.env.GOOGLE_API_KEY
  || process.env.GOOGLE_GEMINI_API_KEY
  || '';

const model = process.env.GEMINI_MODEL
  || process.env.INFINITY_GEMINI_MODEL
  || 'gemini-3.1-flash-lite-image';

const config = `// Auto-generated by Netlify build step
window.INFINITY_GEMINI_API_KEY = ${JSON.stringify(key)};
window.GEMINI_API_KEY = ${JSON.stringify(key)};
window.INFINITY_GEMINI_MODEL = ${JSON.stringify(model)};
window.GEMINI_MODEL = ${JSON.stringify(model)};
`;

await writeFile('ai-config.js', config, 'utf8');

if (key) {
  console.log(`[Netlify Build] Successfully configured Gemini AI key (${key.slice(0, 6)}...${key.slice(-4)}) and model "${model}".`);
} else {
  console.log('[Netlify Build] Note: No Gemini API key detected in environment variables. Set GEMINI_API_KEY in Netlify Site Configuration -> Environment Variables.');
}
